const rooms = new Map();

function shuffle(array) {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

function generateRoomCode() {
  let code;
  do {
    code = Math.floor(1000 + Math.random() * 9000).toString();
  } while (rooms.has(code));
  return code;
}

function generateBunker(playerCount) {
  const capacity = Math.ceil(playerCount / 2);
  const location = shuffle(BUNKER_LOCATIONS)[0];
  const duration = shuffle(BUNKER_DURATIONS)[0];
  const equipment = shuffle(BUNKER_EQUIPMENT).slice(0, 3);
  const quirk = shuffle(BUNKER_QUIRKS)[0];

  return {
    capacity,
    location,
    duration,
    equipment,
    quirk
  };
}

function dealCardsToPlayers(players) {
  const pools = {};
  for (const key of Object.keys(TRAITS)) {
    pools[key] = shuffle(TRAITS[key]);
  }

  players.forEach((player, idx) => {
    const card = {};
    TRAIT_META.forEach(({ key, label, icon }) => {
      card[key] = {
        key,
        label,
        icon,
        value: pools[key][idx % pools[key].length],
        revealed: false
      };
    });
    player.card = card;
    player.isAlive = true;
    player.votedFor = null;
  });
}

// Формирует безопасный слепок состояния комнаты для каждого конкретного игрока
function serializeRoomForPlayer(room, viewerPlayerId) {
  const publicPlayers = room.players.map((p) => {
    const isSelf = p.id === viewerPlayerId;
    const serializedCard = {};

    if (p.card) {
      for (const [k, trait] of Object.entries(p.card)) {
        serializedCard[k] = {
          key: trait.key,
          label: trait.label,
          icon: trait.icon,
          revealed: trait.revealed,
          // Свои характеристики видны владельцу, чужие — только если вскрыты (или игра окончена)
          value: (isSelf || trait.revealed || room.status === 'ended') ? trait.value : 'Скрыто'
        };
      }
    }

    return {
      id: p.id,
      name: p.name,
      isHost: p.id === room.hostId,
      isAlive: p.isAlive,
      isOnline: p.isOnline,
      hasVoted: Boolean(p.votedFor),
      votedFor: room.status === 'voting' && isSelf ? p.votedFor : null,
      card: p.card ? serializedCard : null
    };
  });

  return {
    code: room.code,
    status: room.status,
    hostId: room.hostId,
    round: room.round,
    allowTestMode: room.allowTestMode,
    catastrophe: room.catastrophe,
    bunker: room.bunker,
    players: publicPlayers,
    logs: room.logs.slice(-25),
    lastVoteResult: room.lastVoteResult
  };
}

function broadcastRoomState(room) {
  for (const player of room.players) {
    if (player.socketId) {
      io.to(player.socketId).emit('room:state', serializeRoomForPlayer(room, player.id));
    }
  }
}

function addRoomLog(room, message, type = 'info') {
  const time = new Date().toLocaleTimeString('ru-RU', { hour: '2-digit', minute: '2-digit', second: '2-digit' });
  room.logs.push({ id: Date.now() + Math.random(), time, message, type });
}

