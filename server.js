io.on('connection', (socket) => {
  let currentRoomCode = null;
  let currentPlayerId = null;

  // 1. Создание комнаты
  socket.on('room:create', ({ name, playerId }, callback) => {
    const cleanName = (name || '').trim().slice(0, 20);
    if (!cleanName) return callback({ error: 'Введите ваше имя позывной!' });

    const code = generateRoomCode();
    const pid = playerId || `p_${Math.random().toString(36).slice(2, 10)}`;

    const room = {
      code,
      hostId: pid,
      status: 'lobby', // lobby | playing | voting | ended
      round: 1,
      allowTestMode: false, // если true, разрешает старт от 2 игроков для быстрой проверки
      catastrophe: null,
      bunker: null,
      players: [
        {
          id: pid,
          socketId: socket.id,
          name: cleanName,
          isAlive: true,
          isOnline: true,
          card: null,
          votedFor: null
        }
      ],
      logs: [],
      lastVoteResult: null
    };

    rooms.set(code, room);
    currentRoomCode = code;
    currentPlayerId = pid;
    socket.join(code);

    addRoomLog(room, `Командир «${cleanName}» создал бункер #${code}.`, 'system');
    broadcastRoomState(room);
    callback({ success: true, code, playerId: pid });
  });

  // 2. Присоединение к комнате (или реконнект)
  socket.on('room:join', ({ code, name, playerId }, callback) => {
    const cleanCode = (code || '').trim();
    const cleanName = (name || '').trim().slice(0, 20);
    const room = rooms.get(cleanCode);

    if (!room) {
      return callback({ error: 'Бункер с таким кодом не найден!' });
    }

    const pid = playerId || `p_${Math.random().toString(36).slice(2, 10)}`;
    const existingPlayer = room.players.find((p) => p.id === pid);

    if (existingPlayer) {
      // Переподключение существующего игрока
      existingPlayer.socketId = socket.id;
      existingPlayer.isOnline = true;
      if (cleanName) existingPlayer.name = cleanName;
      currentRoomCode = cleanCode;
      currentPlayerId = pid;
      socket.join(cleanCode);
      broadcastRoomState(room);
      return callback({ success: true, code: cleanCode, playerId: pid, reconnected: true });
    }

    if (!cleanName) {
      return callback({ error: 'Введите ваше имя!' });
    }

    if (room.status !== 'lobby') {
      return callback({ error: 'Гермодвери уже закрыты! Игра в этой комнате началась.' });
    }

    if (room.players.length >= 12) {
      return callback({ error: 'В комнате максимум игроков (12 из 12)!' });
    }

    room.players.push({
      id: pid,
      socketId: socket.id,
      name: cleanName,
      isAlive: true,
      isOnline: true,
      card: null,
      votedFor: null
    });

    currentRoomCode = cleanCode;
    currentPlayerId = pid;
    socket.join(cleanCode);

    addRoomLog(room, `Выживший «${cleanName}» прибыл к шлюзу.`, 'info');
    broadcastRoomState(room);
    callback({ success: true, code: cleanCode, playerId: pid });
  });

  // Переключение тестового режима (для проверки от 2 игроков)
  socket.on('room:toggleTestMode', () => {
    const room = rooms.get(currentRoomCode);
    if (!room || room.hostId !== currentPlayerId || room.status !== 'lobby') return;
    room.allowTestMode = !room.allowTestMode;
    broadcastRoomState(room);
  });

  // 3. Запуск игры (только Хост)
  socket.on('game:start', (_, callback) => {
    const room = rooms.get(currentRoomCode);
    if (!room) return;
    if (room.hostId !== currentPlayerId) {
      return callback?.({ error: 'Только хост может запустить игру!' });
    }

    const minPlayers = room.allowTestMode ? 2 : 4;
    if (room.players.length < minPlayers || room.players.length > 12) {
      return callback?.({
        error: `Для старта нужно от ${minPlayers} до 12 игроков (сейчас: ${room.players.length}).`
      });
    }

    room.status = 'playing';
    room.round = 1;
    room.lastVoteResult = null;
    room.catastrophe = shuffle(CATASTROPHES)[0];
    room.bunker = generateBunker(room.players.length);
    dealCardsToPlayers(room.players);

    addRoomLog(
      room,
      `СИРЕНА! Катастрофа: «${room.catastrophe.title}». Мест в бункере: ${room.bunker.capacity} из ${room.players.length}.`,
      'alert'
    );

    broadcastRoomState(room);
    io.to(room.code).emit('game:toast', {
      icon: '☢️',
      title: 'Игра началась!',
      text: `Мест в бункере: ${room.bunker.capacity}. Изучите свое досье.`
    });
    callback?.({ success: true });
  });

  // 4. Вскрытие характеристики
  socket.on('card:reveal', ({ traitKey }) => {
    const room = rooms.get(currentRoomCode);
    if (!room || (room.status !== 'playing' && room.status !== 'voting')) return;

    const player = room.players.find((p) => p.id === currentPlayerId);
    if (!player || !player.isAlive || !player.card) return;

    const trait = player.card[traitKey];
    if (!trait || trait.revealed) return;

    trait.revealed = true;

    addRoomLog(
      room,
      `${player.name} вскрыл [${trait.label}]: ${trait.value}`,
      'reveal'
    );

    broadcastRoomState(room);

    // Моментальное уведомление для всех игроков
    io.to(room.code).emit('game:toast', {
      icon: trait.icon,
      title: `${player.name} — ${trait.label}`,
      text: trait.value
    });
  });

  // 5. Начало голосования (только Хост)
  socket.on('vote:start', () => {
    const room = rooms.get(currentRoomCode);
    if (!room || room.hostId !== currentPlayerId || room.status !== 'playing') return;

    room.status = 'voting';
    room.lastVoteResult = null;
    room.players.forEach((p) => {
      p.votedFor = null;
    });

    addRoomLog(room, `Раунд ${room.round}: Начато голосование на изгнание!`, 'vote');
    broadcastRoomState(room);
    io.to(room.code).emit('game:toast', {
      icon: '⚖️',
      title: 'Голосование открыто!',
      text: 'Выберите, кто не достоин попасть в бункер.'
    });
  });

  // 6. Голос игрока
  socket.on('vote:cast', ({ targetId }) => {
    const room = rooms.get(currentRoomCode);
    if (!room || room.status !== 'voting') return;

    const voter = room.players.find((p) => p.id === currentPlayerId);
    const target = room.players.find((p) => p.id === targetId);

    if (!voter || !voter.isAlive || !target || !target.isAlive) return;

    voter.votedFor = targetId;
    broadcastRoomState(room);

    // Проверяем, все ли живые игроки проголосовали
    const alivePlayers = room.players.filter((p) => p.isAlive);
    const allVoted = alivePlayers.every((p) => Boolean(p.votedFor));

    if (allVoted) {
      finalizeVoting(room);
    }
  });

  // Принудительное завершение голосования Хостом (если кто-то отошел)
  socket.on('vote:forceEnd', () => {
    const room = rooms.get(currentRoomCode);
    if (!room || room.hostId !== currentPlayerId || room.status !== 'voting') return;
    finalizeVoting(room);
  });

  // Перезапуск в лобби / Новая игра в той же комнате (только Хост)
  socket.on('game:restart', () => {
    const room = rooms.get(currentRoomCode);
    if (!room || room.hostId !== currentPlayerId) return;

    room.status = 'lobby';
    room.round = 1;
    room.catastrophe = null;
    room.bunker = null;
    room.lastVoteResult = null;
    room.players.forEach((p) => {
      p.isAlive = true;
      p.card = null;
      p.votedFor = null;
    });

    addRoomLog(room, 'Хост перезапустил партию. Все вернулись в лобби.', 'system');
    broadcastRoomState(room);
  });

  // Выход из комнаты
  socket.on('room:leave', () => {
    handleLeave(socket, true);
  });

  socket.on('disconnect', () => {
    handleLeave(socket, false);
  });

  function handleLeave(sock, permanent) {
    if (!currentRoomCode) return;
    const room = rooms.get(currentRoomCode);
    if (!room) return;

    const playerIdx = room.players.findIndex((p) => p.id === currentPlayerId);
    if (playerIdx === -1) return;
    const player = room.players[playerIdx];

    if (permanent || room.status === 'lobby') {
      room.players.splice(playerIdx, 1);
      addRoomLog(room, `${player.name} покинул комнату.`, 'info');

      if (room.players.length === 0) {
        rooms.delete(currentRoomCode);
        return;
      }

      if (room.hostId === player.id) {
        room.hostId = room.players[0].id;
        addRoomLog(room, `${room.players[0].name} назначен новым командиром комнаты.`, 'system');
      }
    } else {
      player.isOnline = false;
    }

    broadcastRoomState(room);
  }
});

function finalizeVoting(room) {
  const alivePlayers = room.players.filter((p) => p.isAlive);
  const tally = {};
  const breakdown = [];

  alivePlayers.forEach((p) => {
    tally[p.id] = 0;
  });

  alivePlayers.forEach((voter) => {
    if (voter.votedFor && tally[voter.votedFor] !== undefined) {
      tally[voter.votedFor] += 1;
      const target = room.players.find((p) => p.id === voter.votedFor);
      if (target) {
        breakdown.push({ voterName: voter.name, targetName: target.name });
      }
    }
  });

  let maxVotes = 0;
  for (const count of Object.values(tally)) {
    if (count > maxVotes) maxVotes = count;
  }

  const leaders = alivePlayers.filter((p) => tally[p.id] === maxVotes && maxVotes > 0);

  if (leaders.length === 1) {
    const exiled = leaders[0];
    exiled.isAlive = false;

    room.lastVoteResult = {
      status: 'exiled',
      exiledName: exiled.name,
      votes: maxVotes,
      breakdown
    };

    addRoomLog(
      room,
      `ИТОГ ГОЛОСОВАНИЯ: «${exiled.name}» изгнан из бункера (${maxVotes} гол.)!`,
      'alert'
    );

    io.to(room.code).emit('game:toast', {
      icon: '🚪',
      title: `${exiled.name} изгнан!`,
      text: `Набрано голосов против: ${maxVotes}`
    });
  } else {
    const tiedNames = leaders.map((l) => l.name).join(', ');
    room.lastVoteResult = {
      status: 'tie',
      tiedNames: tiedNames || 'Никто не проголосовал',
      votes: maxVotes,
      breakdown
    };

    addRoomLog(
      room,
      `ИТОГ ГОЛОСОВАНИЯ: Ничья (${tiedNames || 'нет голосов'}). В этом круге никто не изгнан!`,
      'vote'
    );

    io.to(room.code).emit('game:toast', {
      icon: '⚖️',
      title: 'Ничья на голосовании!',
      text: 'Голоса разделились поровну. Никто не изгнан.'
    });
  }

  // Сбрасываем голоса
  room.players.forEach((p) => {
    p.votedFor = null;
  });

  const remainingAlive = room.players.filter((p) => p.isAlive);

  // Проверка условия финала (осталось игроков <= вместимости бункера)
  if (remainingAlive.length <= room.bunker.capacity) {
    room.status = 'ended';
    const winners = remainingAlive.map((p) => p.name).join(', ');
    addRoomLog(
      room,
      `БУНКЕР ЗАПЕЧАТАН! Выжившие внутри: ${winners}.`,
      'system'
    );
  } else {
    room.status = 'playing';
    room.round += 1;
  }

  broadcastRoomState(room);
}

